use std::fmt;
use std::ops::{Bound, Deref, RangeBounds};

use crate::{Key, LookupIndex, Relation, Row};

/// A row and its id.
pub struct Ref<'a, T: Row> {
    id: T::Key,
    row: &'a T,
}

impl<'a, T: Row> Ref<'a, T> {
    pub fn new(id: T::Key, row: &'a T) -> Self {
        Self { id, row }
    }

    pub fn id(&self) -> T::Key {
        self.id
    }

    pub fn row(&self) -> &'a T {
        self.row
    }
}

impl<T: Row> Clone for Ref<'_, T> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<T: Row> Copy for Ref<'_, T> {}

impl<T: Row> Deref for Ref<'_, T> {
    type Target = T;

    fn deref(&self) -> &T {
        self.row
    }
}

impl<T: Row + fmt::Debug> fmt::Debug for Ref<'_, T> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{:?} {:?}", self.id, self.row)
    }
}

/// Gets the index on one column from a relation's indexes.
type IndexFn<T, K> = for<'a> fn(&'a <T as Row>::Indexes) -> &'a dyn LookupIndex<K, <T as Row>::Key>;

/// A column of `T` with values of type `K`. Generated by `#[derive(Relation)]` as
/// a const per field in a module named after the row type, e.g. `post::author`.
pub struct Column<T: Row, K> {
    #[doc(hidden)]
    pub name: &'static str,
    #[doc(hidden)]
    pub get: fn(&T) -> &K,
    #[doc(hidden)]
    pub get_mut: fn(&mut T) -> &mut K,
    /// The index on this column alone, if it has one.
    #[doc(hidden)]
    pub index: Option<IndexFn<T, K>>,
}

impl<T: Row, K> Clone for Column<T, K> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<T: Row, K> Copy for Column<T, K> {}

impl<T: Row, K> Column<T, K> {
    pub fn name(&self) -> &'static str {
        self.name
    }

    pub fn get<'a>(&self, row: &'a T) -> &'a K {
        (self.get)(row)
    }
}

impl<T: Row> Relation<T> {
    /// Rows whose `column` equals `key`. Uses the column's index if it has one, otherwise scans.
    pub fn find<K: PartialEq + 'static>(
        &self,
        column: Column<T, K>,
        key: K,
    ) -> Box<dyn Iterator<Item = Ref<'_, T>> + '_> {
        match column.index {
            Some(index) => {
                let ids = index(self.indexes()).lookup(&key);
                Box::new(ids.map(|id| self.indexed(id)))
            }
            None => Box::new(self.iter().filter(move |r| *column.get(r) == key)),
        }
    }

    /// Rows whose `column` is in `range`. Uses the column's index if it is ordered, otherwise scans.
    pub fn find_range<K: Ord + Clone + 'static>(
        &self,
        column: Column<T, K>,
        range: impl RangeBounds<K>,
    ) -> Box<dyn Iterator<Item = Ref<'_, T>> + '_> {
        let bounds = (range.start_bound().cloned(), range.end_bound().cloned());
        if let Some(index) = column.index
            && let Some(ids) = index(self.indexes()).range(bounds.clone())
        {
            return Box::new(ids.map(|id| self.indexed(id)));
        }
        Box::new(self.iter().filter(move |r| contains(&bounds, column.get(r))))
    }
}

fn contains<K: Ord>(bounds: &(Bound<K>, Bound<K>), key: &K) -> bool {
    bounds.contains(key)
}

/// A column type that can refer to a row with key `K`: `K` itself or `Option<K>`.
pub trait RefersTo<K: Key>: PartialEq + 'static {
    fn refer(key: K) -> Self;
}

impl<K: Key> RefersTo<K> for K {
    fn refer(key: K) -> Self {
        key
    }
}

impl<K: Key> RefersTo<K> for Option<K> {
    fn refer(key: K) -> Self {
        Some(key)
    }
}

/// Joins on iterators of rows.
pub trait Join<'a, P: Row>: Iterator<Item = Ref<'a, P>> + Sized + 'a {
    /// For each row `p`, every row of `relation` whose `column` refers to `p`.
    fn join<C: Row, F: RefersTo<P::Key>>(
        self,
        relation: &'a Relation<C>,
        column: Column<C, F>,
    ) -> impl Iterator<Item = (Ref<'a, P>, Ref<'a, C>)> + 'a {
        self.flat_map(move |p| relation.find(column, F::refer(p.id())).map(move |c| (p, c)))
    }
}

impl<'a, P: Row, I: Iterator<Item = Ref<'a, P>> + 'a> Join<'a, P> for I {}
